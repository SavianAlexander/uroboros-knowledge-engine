@dataclass
class BridgeContract:
    contract_id: str
    bridge_name: str
    protocol_version: str = "1.0.0-PRO"
    timestamp: str = ""
    execution_mode: str = "async_parallel"
    status: str = "SUCCESS"  # SUCCESS | WARNING | FAILED | SKIPPED
    duration_ms: float = 0.0
    inputs: Dict[str, Any] = field(default_factory=dict)
    outputs: Dict[str, Any] = field(default_factory=dict)
    shared_context: Dict[str, Any] = field(default_factory=dict)
    consumed_contracts: List[str] = field(default_factory=list)
    artifacts: List[str] = field(default_factory=list)
    contract_hash: str = ""

    def __post_init__(self):
        if not self.timestamp:
            self.timestamp = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
        if not self.contract_hash:
            self.contract_hash = self.compute_hash()

    def compute_hash(self) -> str:
        """Calculate SHA-256 Merkle signature of the contract contents."""
        payload = f"{self.contract_id}|{self.bridge_name}|{self.status}|{json.dumps(self.outputs, sort_keys=True)}"
        return hashlib.sha256(payload.encode("utf-8")).hexdigest()

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


class InterBridgeEventBus:
    """
    Asynchronous Inter-Bridge Shared Context and Contract Event Bus.
    Allows bridges to register contracts, query peer outputs, and resolve cross-bridge contracts.
    """

    def __init__(self, repo_root: str = "."):
        self.repo_root = os.path.abspath(repo_root)
        self.contracts: Dict[str, BridgeContract] = {}
        self.shared_memory: Dict[str, Any] = {}
        self.ledger_dir = os.path.join(self.repo_root, "docs", "bridge_contracts")
        os.makedirs(self.ledger_dir, exist_ok=True)

    def publish_contract(self, contract: BridgeContract) -> None:
        """Store contract and merge exported context into shared memory."""
        self.contracts[contract.bridge_name] = contract
        if contract.shared_context:
            self.shared_memory.update(contract.shared_context)

    def get_contract(self, bridge_name: str) -> Optional[BridgeContract]:
        """Retrieve latest contract generated by a specific bridge."""
        return self.contracts.get(bridge_name)

    def get_shared_value(self, key: str, default: Any = None) -> Any:
        """Read a value exported by an upstream bridge into shared memory."""
        return self.shared_memory.get(key, default)

    def export_ledger(self) -> str:
        """
        Persist the complete execution ledger to JSON and formatted Markdown report.
        """
        ledger_file = os.path.join(self.ledger_dir, "execution_ledger.json")
        report_file = os.path.join(self.ledger_dir, "contract_audit_ledger.md")

        ledger_data = {
            "ledger_id": f"ledger_{int(time.time())}",
            "timestamp": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
            "total_bridges_executed": len(self.contracts),
            "all_contracts_verified": all(c.status in ["SUCCESS", "WARNING"] for c in self.contracts.values()),
            "shared_memory_snapshot": self.shared_memory,
            "contracts": {k: v.to_dict() for k, v in self.contracts.items()}
        }

        # 1. Save JSON Ledger
        with open(ledger_file, "w", encoding="utf-8") as f:
            json.dump(ledger_data, f, indent=2)

        # 2. Save Markdown Audit Report
        with open(report_file, "w", encoding="utf-8") as f:
            f.write("# 🏛️ Inter-Bridge Contract & Parallel Execution Ledger\n\n")
            f.write(f"* **Execution Timestamp:** `{ledger_data['timestamp']}`\n")
            f.write(f"* **Ledger ID:** `{ledger_data['ledger_id']}`\n")
            f.write(f"* **Participating Bridges:** {len(self.contracts)}\n")
            f.write(f"* **Integrity Status:** {'✅ 100% Verified' if ledger_data['all_contracts_verified'] else '⚠️ Verification Failures Detected'}\n\n")
            f.write("---\n\n")

            f.write("## 📜 Verified Bridge Contracts Matrix\n\n")
            f.write("| Bridge Name | Status | Duration | Contract Hash (SHA-256) | Key Output / Metrics |\n")
            f.write("| :--- | :---: | :---: | :--- | :--- |\n")

            for name, c in self.contracts.items():
                short_hash = f"`{c.contract_hash[:12]}...{c.contract_hash[-6:]}`"
                metric_summary = ", ".join([f"{k}: {v}" for k, v in list(c.outputs.items())[:2]])
                f.write(f"| **`{name}`** | `{c.status}` | `{c.duration_ms:.1f}ms` | {short_hash} | {metric_summary} |\n")

            f.write("\n---\n\n")
            f.write("## 🔄 Shared Cross-Bridge Context State\n\n")
            f.write("```json\n")
            f.write(json.dumps(self.shared_memory, indent=2))
            f.write("\n```\n")

        return ledger_file


